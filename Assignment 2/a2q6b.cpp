#include <iostream>
using namespace std;
int main() {
    int a[3][3]={{3,3,2},{0,0,5},{1,2,8}}, b[3][3]={{3,3,2},{0,0,3},{1,2,6}}, c[5][3];
    c[0][0]=a[0][0]; c[0][1]=a[0][1];
    int i=1,j=1,k=1;
    while(i<=a[0][2] && j<=b[0][2]){
        if(a[i][0]==b[j][0] && a[i][1]==b[j][1]){ c[k][0]=a[i][0]; c[k][1]=a[i][1]; c[k++][2]=a[i++][2]+b[j++][2]; }
        else if(a[i][0]<b[j][0]||(a[i][0]==b[j][0]&&a[i][1]<b[j][1])) c[k][0]=a[i][0],c[k][1]=a[i][1],c[k++][2]=a[i++][2];
        else c[k][0]=b[j][0],c[k][1]=b[j][1],c[k++][2]=b[j++][2];
    }
    while(i<=a[0][2]) c[k][0]=a[i][0],c[k][1]=a[i][1],c[k++][2]=a[i++][2];
    while(j<=b[0][2]) c[k][0]=b[j][0],c[k][1]=b[j][1],c[k++][2]=b[j++][2];
    c[0][2]=k-1;
    for(int p=0;p<k;p++) cout<<c[p][0]<<" "<<c[p][1]<<" "<<c[p][2]<<endl;
}